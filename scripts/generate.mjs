/**
 * Pull the published Flowella OpenAPI document and emit the contract the
 * community node is generated from. `--check` fails when the committed
 * output would change, and names the operations or fields that drifted.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const contractPath = resolve(root, 'nodes/Flowella/generated/contract.json');
const routesPath = resolve(root, 'nodes/Flowella/generated/routes.ts');
const nodePath = resolve(root, 'nodes/Flowella/Flowella.node.ts');
const packagePath = resolve(root, 'package.json');

const DEFAULT_URL = 'https://api.flowella.io/v1/openapi.json';

/** Epic scope (FLOV2-583). Ping is the credential test. */
const SCOPE = [
	['GET', '/v1/ping', 'ping'],
	['POST', '/v1/messages', 'messageSend'],
	['GET', '/v1/conversations', 'conversationList'],
	['GET', '/v1/contacts', 'contactList'],
	['POST', '/v1/contacts', 'contactUpsert'],
	['POST', '/v1/opt-outs', 'optOut'],
	['GET', '/v1/templates', 'templateList'],
	['POST', '/v1/templates/send', 'templateSend'],
	['GET', '/v1/analytics', 'analyticsGet'],
];

function sortValue(value) {
	if (Array.isArray(value)) return value.map(sortValue);
	if (value && typeof value === 'object') {
		const out = {};
		for (const key of Object.keys(value).sort()) out[key] = sortValue(value[key]);
		return out;
	}
	return value;
}

function schemaFields(schema) {
	if (!schema || typeof schema !== 'object') return [];
	if (Array.isArray(schema.oneOf)) {
		const names = new Set();
		for (const branch of schema.oneOf) {
			for (const name of Object.keys(branch.properties ?? {})) names.add(name);
		}
		return [...names].sort();
	}
	return Object.keys(schema.properties ?? {}).sort();
}

function buildContract(document) {
	const operations = {};
	for (const [method, path, key] of SCOPE) {
		const op = document.paths?.[path]?.[method.toLowerCase()];
		if (!op) {
			throw new Error(`OpenAPI document has no ${method} ${path}`);
		}
		const parameters = (op.parameters ?? [])
			.filter((parameter) => parameter.in === 'query' || parameter.in === 'path')
			.map((parameter) => ({
				name: parameter.name,
				in: parameter.in,
				required: Boolean(parameter.required),
			}))
			.sort((a, b) => a.name.localeCompare(b.name));
		const bodySchema = op.requestBody?.content?.['application/json']?.schema;
		operations[key] = {
			method,
			path,
			operationId: op.operationId ?? null,
			query: parameters
				.filter((parameter) => parameter.in === 'query')
				.map((parameter) => parameter.name),
			body: schemaFields(bodySchema),
		};
	}
	return sortValue({
		contractVersion: document.info?.version ?? 'unknown',
		source: process.env.FLOWELLA_OPENAPI_URL || DEFAULT_URL,
		operations,
	});
}

function renderRoutes(contract) {
	const lines = [
		'/* Generated by scripts/generate.mjs. Do not edit. */',
		`export const flowellaApiContract = ${JSON.stringify(contract.contractVersion)};`,
		'',
		'export const flowellaRoutes = {',
	];
	for (const [key, operation] of Object.entries(contract.operations)) {
		lines.push(
			`  ${key}: { method: ${JSON.stringify(operation.method)}, path: ${JSON.stringify(operation.path)} },`,
		);
	}
	lines.push('} as const;', '');
	return lines.join('\n');
}

function fieldNames(contract) {
	const names = new Set();
	for (const operation of Object.values(contract.operations)) {
		for (const name of operation.query) names.add(name);
		for (const name of operation.body) names.add(name);
	}
	return [...names].sort();
}

function diffKeys(previous, next) {
	const changes = [];
	const keys = new Set([
		...Object.keys(previous.operations ?? {}),
		...Object.keys(next.operations),
	]);
	for (const key of [...keys].sort()) {
		const before = JSON.stringify(previous.operations?.[key] ?? null);
		const after = JSON.stringify(next.operations?.[key] ?? null);
		if (before !== after) changes.push(key);
	}
	if (previous.contractVersion !== next.contractVersion) changes.push('contractVersion');
	return changes;
}

const url = process.env.FLOWELLA_OPENAPI_URL || DEFAULT_URL;
const response = await fetch(url);
if (!response.ok) {
	throw new Error(`Failed to fetch OpenAPI (${response.status}) from ${url}`);
}
const document = await response.json();
const contract = buildContract(document);
const contractText = `${JSON.stringify(contract, null, 2)}\n`;
const routesText = renderRoutes(contract);
const check = process.argv.includes('--check');

if (check) {
	const previous = JSON.parse(readFileSync(contractPath, 'utf8'));
	const previousRoutes = readFileSync(routesPath, 'utf8');
	const nodeSource = readFileSync(nodePath, 'utf8');
	const missing = fieldNames(contract).filter((name) => !nodeSource.includes(name));
	const changes = diffKeys(previous, contract);
	const routesChanged = Object.entries(contract.operations).some(
		([key, operation]) =>
			!previousRoutes.includes(`${key}:`) || !previousRoutes.includes(operation.path),
	);
	void routesText;
	if (changes.length || routesChanged || missing.length) {
		console.error('Flowella OpenAPI contract drift.');
		if (changes.length) console.error(`Changed operations: ${changes.join(', ')}`);
		if (missing.length) console.error(`Node is missing fields: ${missing.join(', ')}`);
		process.exit(1);
	}
	const pkg = JSON.parse(readFileSync(packagePath, 'utf8'));
	if (pkg.flowellaApiContract !== contract.contractVersion) {
		console.error(
			`package.json flowellaApiContract is ${pkg.flowellaApiContract}, OpenAPI info.version is ${contract.contractVersion}`,
		);
		process.exit(1);
	}
	console.log(`Contract ${contract.contractVersion} matches the committed node.`);
} else {
	mkdirSync(dirname(contractPath), { recursive: true });
	writeFileSync(contractPath, contractText);
	writeFileSync(routesPath, routesText);
	const pkg = JSON.parse(readFileSync(packagePath, 'utf8'));
	pkg.flowellaApiContract = contract.contractVersion;
	writeFileSync(packagePath, `${JSON.stringify(pkg, null, 4)}\n`);
	console.log(`Wrote contract ${contract.contractVersion} from ${url}`);
}
